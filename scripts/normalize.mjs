// 中文里厨具的中心词在末尾（耐热碗/厚底锅/刨丝器/厨房纸），按后缀判定比穷举词表可靠。
// "火锅底料""锅巴""火锅牛肉卷"不以这些字结尾，不会被误伤。
const TOOL_SUFFIX = /(锅|碗|盆|器|机|纸|勺|刀|板|签|夹|布|袋|模|秤|表|架|网|膜|棒|杖|筒|铲|钳|计|垫|皿|箱|炉|柜)$/;
const TOOL_WORDS = /微波炉|烤箱|案板|砧板|漏勺|刷子|手套|保鲜膜|锡纸|裱花袋|温度计|擀面杖|筷子|牙签|棉线|纱布|蒸屉|容器|定时器|电饭煲/;
const TOOLS = { test: (s) => TOOL_SUFFIX.test(s) || TOOL_WORDS.test(s) };

// 只剥几乎不可能构成食材本名的后缀。"薯条""粉条""土豆丝"里的条/丝是名字的一部分，
// 剥了会毁掉词义——那类差异交给 matcher 的子串匹配处理，不在这里硬剥。
const CUT_SUFFIX = /(段|末|碎|泥)$/;

const UNIT = 'g|kg|克|千克|ml|毫升|升|L|斤|两|个|颗|根|片|块|把|勺|袋|条|只|滴|杯|瓣';
const LEAD_QTY = new RegExp('^[0-9.]+[ ]*(?:-[ ]*[0-9.]+)?[ ]*(?:' + UNIT + ')?[ ]*');
const TAIL_QTY = new RegExp('[ ]+[0-9.]+[ ]*(?:-[ ]*[0-9.]+)?[ ]*(?:' + UNIT + ')?$');
const TAIL_CN_QTY = new RegExp(`(?:一|两|二|三|四|五|半)(?:${UNIT})$`);

export function normalizeIngredient(raw) {
  const optional = /（可选）|\(可选\)|\[可选\]/.test(raw);
  const cleaned = raw
    .replace(/!\[[^\]]*\]\([^)]*\)/g, '')      // 图片语法
    .replace(/!?\[[^\]]*\]/g, '')              // 残留方括号标记，如 [可选]
    .replace(/（[^）]*）|\([^)]*\)/g, '')       // 括号注释
    .replace(/\s*[:：].*$/, '');
  return cleaned
    .split(/、|或|\s+or\s+|\s*\/\s*|,/)
    .map((seg) => seg.replace(/，.*$/, '').trim())            // "黑鳕鱼，带皮" -> "黑鳕鱼"
    .map((seg) => seg.replace(/^(适量|少许|些许)/, '').trim())
    .map((seg) => seg.replace(LEAD_QTY, '').trim())           // "125ml 淡奶油" -> "淡奶油"
    .map((seg) => seg.replace(TAIL_QTY, '').trim())           // "牛奶 50-100g" -> "牛奶"
    .map((seg) => seg.replace(TAIL_CN_QTY, '').trim())        // "鱼头一个" -> "鱼头"
    .map((seg) => {                                           // "蛋挞皮 品牌不限" -> "蛋挞皮"
      const first = seg.split(/[ ]+/)[0];
      return first.length >= 2 ? first : seg;
    })
    .filter((seg) => seg && seg.length <= 12)
    .map((seg) => {
      let name = seg;
      if (!ALIAS.has(name) && !SEASONINGS.has(name) && name.length >= 3 && CUT_SUFFIX.test(name)) {
        const stripped = name.replace(CUT_SUFFIX, '');
        if (stripped.length >= 2) name = stripped;
      }
      name = ALIAS.get(name) ?? name;
      return { name, raw, optional, isSeasoning: SEASONINGS.has(name), isTool: TOOLS.test(name) };
    });
}
